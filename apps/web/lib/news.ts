/** Looks up an article by slug, or `undefined` when it does not exist. */
export function getArticle(slug: string): NewsArticle | undefined {
  return NEWS_ARTICLES.find((article) => article.slug === slug);
}

/** Renders an ISO date as `2026.09.28`, which reads naturally in Mongolian. */
export function formatArticleDate(iso: string): string {
  return iso.split('-').join('.');
}
