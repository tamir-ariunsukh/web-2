/**
 * News articles.
 *
 * Static content: the platform has no CMS, and these pages exist to give the
 * marketing site real depth rather than to drive a publishing workflow. Keeping
 * them as a typed module means the list and detail pages cannot drift apart, and
 * `generateStaticParams` can prerender every detail page at build time.
 */

